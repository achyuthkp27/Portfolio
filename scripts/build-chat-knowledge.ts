/**
 * Writes the chat assistant's knowledge (src/lib/chatKnowledge.ts, built from src/data) to
 * api/_knowledge.ts, where the serverless chat function reads it. Run after editing anything in
 * src/data: `npm run chat:knowledge`. Runs under plain Node with type stripping.
 */
import { writeFileSync } from "node:fs";
import { buildKnowledge } from "../src/lib/chatKnowledge.ts";

const target = new URL("../api/_knowledge.ts", import.meta.url);
const source = `// Generated by scripts/build-chat-knowledge.ts from src/data. Do not edit: run \`npm run chat:knowledge\`.
export const KNOWLEDGE = ${JSON.stringify(buildKnowledge())};
`;
writeFileSync(target, source);
console.log(`Wrote ${target.pathname} (${source.length} characters)`);
